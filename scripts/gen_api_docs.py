"""Generate docs/API.md from the Flask route decorators (static AST scan, no DB needed).

    python scripts/gen_api_docs.py
"""
import ast
import collections
import glob
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
PUBLIC = {"login", "add_user"}


def collect():
    rows = []
    files = sorted(set(glob.glob(str(ROOT / "app/*/route*.py")) + glob.glob(str(ROOT / "app/*/*routes.py"))))
    for f in files:
        module = pathlib.Path(f).parent.name
        tree = ast.parse(pathlib.Path(f).read_text(encoding="utf-8"))
        for fn in ast.walk(tree):
            if not isinstance(fn, ast.FunctionDef):
                continue
            auth = fn.name not in PUBLIC
            for d in fn.decorator_list:
                if isinstance(d, ast.Call) and isinstance(d.func, ast.Attribute) and d.func.attr == "route":
                    path = d.args[0].value if d.args and isinstance(d.args[0], ast.Constant) else "?"
                    methods = ["GET"]
                    for kw in d.keywords:
                        if kw.arg == "methods":
                            methods = [e.value for e in kw.value.elts if e.value != "OPTIONS"]
                    doc = (ast.get_docstring(fn) or fn.name.replace("_", " ")).strip().split("\n")[0]
                    rows.append((module, path, "/".join(methods), auth, doc))
    return rows


def main():
    rows = collect()
    by_module = collections.defaultdict(list)
    for r in rows:
        by_module[r[0]].append(r)
    out = ["# API reference", "",
           f"{len(rows)} routes (+ `GET /api/v1/health`). Generated by `scripts/gen_api_docs.py`.",
           "All routes except login and registration require `Authorization: Bearer <JWT>`.", ""]
    for module in sorted(by_module):
        out += [f"## {module}", "", "| Method | Route | Description | Auth |", "|---|---|---|---|"]
        for _, path, methods, auth, doc in sorted(by_module[module], key=lambda r: r[1]):
            out.append(f"| {methods} | `{path}` | {doc.replace('|', '/')} | {'JWT' if auth else 'public'} |")
        out.append("")
    (ROOT / "docs" / "API.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote docs/API.md ({len(rows)} routes)")


if __name__ == "__main__":
    main()
